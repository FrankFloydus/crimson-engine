const CommandBehaviorContract *
find_command_behavior_contract(std::string_view command_id) {
  for (const CommandBehaviorContract &contract :
       command_behavior_contracts()) {
    if (contract.command_id == command_id) {
      return &contract;
    }
  }
  return nullptr;
}

