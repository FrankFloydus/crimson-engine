[[nodiscard]] constexpr CommandBehaviorContract
contract(QuaderCommandId command_id, Fixture fixture, Domain domains,
         Outcome outcome, UndoRepeat undo_repeat = UndoRepeat::None,
         Flags flags = Flags::None) {
  return {
      .command_id = command_id.string(),
      .fixture = fixture,
      .observable_domains = domains,
      .outcome = outcome,
      .undo_repeat = undo_repeat,
      .flags = flags,
  };
}

