bool has_incident_quad(const AuthoredTopology &topology, EdgeKey edge) {
  for (const auto &face : topology.faces) {
    if (face.vertices.size() != 4U) continue;
    for (std::size_t corner = 0U; corner < face.vertices.size(); ++corner) {
      if (make_edge_key(face.vertices[corner],
                        face.vertices[(corner + 1U) % face.vertices.size()]) == edge) {
        return true;
      }
    }
  }
  return false;
}

void expect_preserved_attributes(const PolygonDocument &before,
                                 const PreparedUvPeelDocument &prepared) {
  const auto &after = prepared.document;
  EXPECT_TRUE(after.has_same_geometry(before));
  EXPECT_EQ(after.vertex_ids(), before.vertex_ids());
  EXPECT_EQ(after.edge_ids(), before.edge_ids());
  EXPECT_EQ(after.face_ids(), before.face_ids());
  EXPECT_EQ(after.hard_edge_ids(), before.hard_edge_ids());
  EXPECT_EQ(after.selection_revision(), before.selection_revision());
  EXPECT_TRUE(after.shares_selection_with(before));
  EXPECT_FALSE(prepared.receipt.dirty.topology);
  EXPECT_FALSE(prepared.receipt.dirty.materials);
  EXPECT_FALSE(prepared.receipt.dirty.selection);
  const auto source = before.authored_topology();
  const auto result = after.authored_topology();
  ASSERT_TRUE(source.ok());
  ASSERT_TRUE(result.ok());
  EXPECT_EQ(result.value().next_vertex_id, source.value().next_vertex_id);
  EXPECT_EQ(result.value().next_face_id, source.value().next_face_id);
  ASSERT_EQ(result.value().faces.size(), source.value().faces.size());
  for (std::size_t index = 0U; index < source.value().faces.size(); ++index) {
    const auto &first = source.value().faces[index];
    const auto &last = result.value().faces[index];
    SCOPED_TRACE(first.id.index);
    EXPECT_EQ(last.id, first.id);
    EXPECT_EQ(last.vertices, first.vertices);
    EXPECT_EQ(last.shading, first.shading);
    EXPECT_EQ(last.material_slot, first.material_slot);
    EXPECT_EQ(last.texture_transform, first.texture_transform);
    ASSERT_EQ(last.uvs.size(), last.vertices.size());
    for (const auto uv : last.uvs) {
      EXPECT_TRUE(std::isfinite(uv.x));
      EXPECT_TRUE(std::isfinite(uv.y));
    }
    if (std::ranges::find(prepared.receipt.affected.faces, first.id) ==
        prepared.receipt.affected.faces.end()) {
      ASSERT_EQ(last.uvs.size(), first.uvs.size());
      for (std::size_t corner = 0U; corner < first.uvs.size(); ++corner) {
        EXPECT_EQ(last.uvs[corner].x, first.uvs[corner].x);
        EXPECT_EQ(last.uvs[corner].y, first.uvs[corner].y);
      }
    }
  }
}

