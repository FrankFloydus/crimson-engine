std::optional<QuaderMouseButton> quaderMouseButtonFromSdlButton(std::uint8_t button) {
    switch (button) {
    case SDL_BUTTON_LEFT:
        return QuaderMouseButton::Left;
    case SDL_BUTTON_MIDDLE:
        return QuaderMouseButton::Middle;
    case SDL_BUTTON_RIGHT:
        return QuaderMouseButton::Right;
    case SDL_BUTTON_X1:
        return QuaderMouseButton::Back;
    case SDL_BUTTON_X2:
        return QuaderMouseButton::Forward;
    default:
        return std::nullopt;
    }
}

